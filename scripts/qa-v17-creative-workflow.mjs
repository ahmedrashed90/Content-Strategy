import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {execFileSync} from 'node:child_process';
const source=(file)=>readFileSync(new URL('../'+file,import.meta.url),'utf8');
const js=['site/app.js','site/idea-import.js','site/planner.js','site/plan-firebase.js','site/marketing-bridge.js','site/proposals.js','api/marketing-bridge.js'];
for(const file of js){execFileSync(process.execPath,['--check',new URL('../'+file,import.meta.url).pathname],{stdio:'pipe'});}
const d=JSON.parse(source('data/MZJ-CURRENT-CONTENT-BANK-REVISED-36-IMPORT-20261111.json'));
assert.equal(d.schema,'mzj-ideas-batch/v1');
assert.equal(d.ideas.length,36);
assert.equal(d.ideas.filter(x=>x.type==='video').length,16);
assert.equal(d.ideas.filter(x=>x.type==='image').length,20);
assert.equal(new Set(d.ideas.map(x=>x.code)).size,d.ideas.length);
assert.ok(d.ideas.every(x=>x.title&&x.message&&x.hook&&x.productionNotes));
const app=source('site/app.js'),planner=source('site/planner.js'),rules=source('firestore.rules');
assert.ok(app.includes('async function saveReplacementBatch'));
assert.ok(app.includes('async function savePublishingProposal'));
assert.ok(app.includes('proposals: ()=>proposalsPage(state)'));
assert.ok(planner.includes('idea-replace-verify'));
assert.ok(!planner.includes('<div class="calendar-summary">'));
assert.ok(rules.includes("'retiredFromIdeaBank'")&&rules.includes('publishingProposals'));
const integration=source('api/marketing-bridge.js');
assert.ok(integration.includes("payload.action === 'assign'"));
assert.ok(!integration.includes("payload.action === 'agenda'"));
console.log('v1.7 static QA passed: 36 import ideas, safe retirement, proposal UI and unchanged Marketing assignment API.');
