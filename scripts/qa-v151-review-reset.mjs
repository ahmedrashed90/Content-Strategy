// Offline v1.5.1 test: withdrawing approval never creates or modifies Marketing tasks.
import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import {ideaAssets,ideaIsApproved,REVIEW_STATUSES,reviewStatusFor,assetDetailPage} from '../site/planner.js';

const appSource=fs.readFileSync(new URL('../site/app.js',import.meta.url),'utf8');
const start=appSource.indexOf('async function saveIdeaReview(form,decision){');
const stop=appSource.indexOf('\nasync function savePostEditor(',start);
assert(start>0&&stop>start,'Review function must be found in the real application source');
const fnSource=appSource.slice(start,stop);
const history=[{status:'معتمد',notes:'تمت الموافقة كتجربة',at:'2026-11-11T00:00:00.000Z',reviewedByUid:'owner'}];
const makeAsset=(code,props={})=>({code,kind:'video',title:code,status:'لم يبدأ',executor:'',dueDate:'',reviewStatus:'معتمد',reviewNotes:'تمت الموافقة كتجربة',reviewedAt:'2026-11-11T00:00:00.000Z',reviewedByUid:'owner',reviewHistory:history,creativeApprovedAt:'2026-11-11T01:00:00.000Z',approvedCarMode:'single',approvedVehicles:[{car_name:'سيارة'}],...props});
const plan={assets:[makeAsset('V01'),makeAsset('V02',{reviewStatus:'بانتظار المراجعة',creativeApprovedAt:null})],carousels:[],posts:[]};
const state={plan,planSaving:false,user:{uid:'owner'},selectedAssetCode:'V01'};
const toasts=[],persisted=[];let confirmed=true,shouldFail=false;
const ctx={state,isLocalPreview:false,REVIEW_STATUSES,ideaAssets,ideaIsApproved,toast:s=>toasts.push(s),render:()=>{},console,window:{confirm:()=>confirmed},
  updateManyAssets:async(codes,change)=>{if(shouldFail)throw Error('simulated unavailable');persisted.push({codes,change});}};
vm.createContext(ctx);
vm.runInContext(`${fnSource}\nglobalThis.testReviewReset=saveIdeaReview;`,ctx);
const f=code=>({elements:{namedItem:name=>name==='ideaCode'?{value:code}:{value:''}}});
const run=(code,decision)=>ctx.testReviewReset(f(code),decision);
const before=assetDetailPage({...state});
assert(before.includes('value="بانتظار المراجعة"')&&before.includes('إلغاء الاعتماد وإعادة للمراجعة'));
await run('V01','بانتظار المراجعة');
assert.equal(persisted.length,1);assert.equal(persisted[0].codes[0],'V01');
assert.equal(plan.assets[0].reviewStatus,'بانتظار المراجعة');assert.equal(reviewStatusFor(plan,'V01'),'بانتظار المراجعة');
assert.equal(plan.assets[0].reviewedAt,null);assert.equal(plan.assets[0].reviewNotes,'');
assert.equal(plan.assets[0].approvedVehicles.length,0);assert.equal(plan.assets[0].creativeApprovedAt,null);
assert.equal(plan.assets[0].reviewHistory.length,2);assert.equal(plan.assets[0].reviewHistory.at(-1).status,'بانتظار المراجعة');
const after=assetDetailPage({...state});
assert(after.includes('value="معتمد"')&&!after.includes('إلغاء الاعتماد وإعادة للمراجعة'));
await run('V01','معتمد');assert.equal(reviewStatusFor(plan,'V01'),'معتمد','Approval must work again after reset');
const baseline=persisted.length;
confirmed=false;await run('V01','بانتظار المراجعة');assert.equal(persisted.length,baseline,'Cancel confirmation should not write');confirmed=true;
plan.assets[0].integrationRequestKey='pending-key';
assert(!assetDetailPage({...state}).includes('إلغاء الاعتماد وإعادة للمراجعة'),'Pending request must hide undo button');
await run('V01','بانتظار المراجعة');assert.equal(persisted.length,baseline,'Pending task must block reset');
plan.assets[0].integrationRequestKey='';plan.assets[0].marketingTaskId='TASK-123';await run('V01','بانتظار المراجعة');assert.equal(persisted.length,baseline,'Existing task must block reset');
const linked=assetDetailPage({...state});assert(!linked.includes('إلغاء الاعتماد وإعادة للمراجعة'));
plan.assets[0].marketingTaskId='';shouldFail=true;await run('V01','بانتظار المراجعة');assert.equal(reviewStatusFor(plan,'V01'),'معتمد','Failed save must not change UI locally');
assert(toasts.some(t=>t.includes('تعذر حفظ المراجعة')));
console.log('PASS: one-click re-review, approval recovery, revision history retained, linked-task safety, cancellation and Firestore-failure behavior');
