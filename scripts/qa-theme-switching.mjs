const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const text=p=>fs.readFileSync(path.join(root,p),'utf8');
const source=text('site/app.js'),managerCode=text('site/theme-manager.js');
const storage=new Map();
const themeContext=()=>{
  const attrs=new Map();const children=[];
  const fakeLink={attributes:new Map(),isConnected:false,setAttribute(k,v){this.attributes.set(k,v);},getAttribute(k){return this.attributes.get(k)||null;},removeAttribute(k){this.attributes.delete(k);},remove(){this.isConnected=false;}};
  const document={documentElement:{setAttribute(k,v){attrs.set(k,v);},removeAttribute(k){attrs.delete(k);}},createElement:()=>fakeLink,head:{appendChild(l){children.push(l);l.isConnected=true;}}};
  const listeners={};
  const window={addEventListener(e,fn){listeners[e]=fn;}};
  const localStorage={getItem:k=>storage.get(k)||null,setItem:(k,v)=>storage.set(k,v),removeItem:k=>storage.delete(k)};
  const ctx=vm.createContext({window,document,localStorage});
  vm.runInContext(managerCode,ctx);
  return {ctx,api:window.MZJTheme,attrs,children,fakeLink,listeners,localStorage};
};
const first=themeContext();
assert.equal(first.api.catalog.length,8);
assert.equal(first.api.applied(),'');
assert(!first.attrs.has('data-mzj-theme'),'the approved theme remains unchanged until apply');
for(let n=1;n<=8;n++){
  const id=String(n).padStart(2,'0');
  assert(first.api.preview(id));
  assert.equal(first.attrs.get('data-mzj-theme'),id);
  const css=first.api.catalog[n-1].file;
  assert.equal(first.fakeLink.getAttribute('href'),'./themes/'+css);
  const content=text('site/themes/'+css);
  assert(content.includes('--accent:')&&content.includes('--theme-icon-stroke:')&&content.includes('--theme-button-bg:'));
  assert(!content.includes('Shared visual surfaces'),'themes are token-only plus unique accents');
}
